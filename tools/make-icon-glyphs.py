"""从 Material Symbols Sharp 字体生成图标码位表。

WPF 不会应用这款字体的 rlig（连字）特性，所以不能写 Text="play_arrow"，
必须用私用区码位。本脚本按图标名反查码位，生成 Themes/IconGlyphs.cs。

用法：python tools/make-icon-glyphs.py
"""

import os
import re
from fontTools.ttLib import TTFont

NAMES = [
    "record_voice_over", "expand_more", "expand_less", "settings",
    "folder_open", "folder", "download", "downloading", "play_arrow",
    "play_circle", "pause", "stop", "stop_circle", "arrow_upward",
    "arrow_downward", "graphic_eq", "graphic_eq_off", "search", "check",
    "close", "add", "delete", "content_copy", "more_vert", "refresh",
    "replay", "music_note", "palette", "dark_mode", "light_mode", "tune",
    "speed", "volume_up", "volume_off", "volume_down", "history",
    "text_fields", "description", "file_open", "save_alt", "hourglass_empty",
    "error", "info", "sync", "auto_awesome", "language", "translate",
    "person", "sort", "filter_list", "copy_all", "open_in_new",
    "upload_file", "chevron_right", "arrow_drop_down", "notes",
    "text_snippet", "draft", "bolt", "mic", "equalizer", "headphones",
    "timer", "queue_music", "playlist_play", "link", "tune", "circle",
]


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def main() -> None:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    font_path = os.path.join(root, "assets", "MaterialSymbolsSharp.ttf")
    font = TTFont(font_path)
    cmap = font.getBestCmap()

    by_glyph = {}
    for codepoint, glyph in cmap.items():
        by_glyph.setdefault(glyph, codepoint)

    resolved = []
    missing = []
    for name in dict.fromkeys(NAMES):
        codepoint = by_glyph.get(name)
        if codepoint is None:
            missing.append(name)
            continue
        resolved.append((name, pascal(name), codepoint))

    lines = [
        "// <auto-generated>",
        "// 由 tools/make-icon-glyphs.py 从 assets/MaterialSymbolsSharp.ttf 生成。",
        "// WPF 不应用这款字体的 rlig 连字，所以这里直接用私用区码位。",
        "// 需要新图标时：把名字加进脚本的 NAMES 再重新生成。",
        "// </auto-generated>",
        "namespace ALambdaTTS.Themes;",
        "",
        "public static class IconGlyphs",
        "{",
    ]

    for name, member, codepoint in resolved:
        lines.append(f'    /// <summary>{name}</summary>')
        lines.append(f'    public const string {member} = "\\u{codepoint:04X}";')
        lines.append("")

    lines.append("}")

    target = os.path.join(root, "Themes", "IconGlyphs.cs")
    with open(target, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))

    print(f"生成 {target}，共 {len(resolved)} 个图标")
    if missing:
        print("字体里没有这些名字，已跳过：" + ", ".join(missing))


if __name__ == "__main__":
    main()
